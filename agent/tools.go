type hintItem struct {
	Text        string            `json:"text"`
	AssetIDs    []json.RawMessage `json:"asset_ids"`
	TrafficRefs []db.TrafficRef   `json:"traffic_refs"`
}

// addOneHint Hangs a hint node (active/human) to the exploration map, anchoring the asset, and
// returning id.
func (t *ToolSet) addOneHint(it hintItem) (int64, error) {
	if len(it.TrafficRefs) > 0 && !findingTrafficBindingEnabled() {
		return 0, fmt.Errorf("Agent Automatic binding of traffic is disabled, no saved prompts carrying traffic_refs; can be enabled in system settings, or text only")
	}
	if strings.TrimSpace(it.Text) == "" {
		return 0, fmt.Errorf("Text cannot be empty")
	}
	var anchors []int64
	for _, raw := range it.AssetIDs {
		if tid := pid(raw); tid > 0 {
			anchors = append(anchors, tid)
		}
	}
	refs, err := db.NormalizeTrafficRefs(it.TrafficRefs)
	if err != nil {
		return 0, err
	}
	payload := map[string]any{"text": it.Text}
	if len(refs) > 0 {
		payload["traffic_refs"] = refs
	}
	// The planner is not triggered line by line here — it is triggered once by addHint after the
	// batch is written (with hint text), avoiding a row-by-row trigger of the planner by multiple
	// hints at a time.
	return t.ts.AddNode(db.KindHint, payload, 0, "active", "human", anchors)
}

