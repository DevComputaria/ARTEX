// This document covers the end-to-end behavior of push functions: Vulnerability drop → Event →
// Assignment → HTTP real.
//
// A security note: These use cases** do not call the global Notifier.step()**, but only call
// stepRealtime/stepDigest for channels they have created. This is because step() goes through all
// enabled channels in the library — testing on a real DingTalk/Enterprise bot development library
// that has been set up, and the global step pushes the vulnerabilities created during the test to
// those groups.
//
// Cleanup: At the end of the use case, the events generated by the use case (cascade delete
// delivery) and the channel are deleted, leaving no backlog for the real channel.
//
// Assertion port: stepRealtime/stepDigest does not return values, internally logs, so here the
// assertion is about **observable external behavior** (what the fake receiver received, what the
// input line went to), rather than the return value of the function—which is closer to the real
// call path than picking on the return value.

// notifyFixture is the public device for this document use case.
type notifyFixture struct {
	s       *Server
	pg      *db.DB
	request func(method, path, body string) *httptest.ResponseRecorder
	n       *Notifier
	// Custom task/exploration: Use cases write the vulnerability here, isolated from other use case
	// data.
	taskID int64
	expID  int64
	// Events that occur after cleanupMark are deleted with the cleanup.
	cleanupMark int64
}

func newNotifyFixture(t *testing.T) *notifyFixture {
	t.Helper()
	// All fake receivers in this file run on 127.0.0.1, and deliver the default deny loopback
	// address (prevents SSRF from calling the peer service and cloud metadata). Test explicitly
	// turns this switch on; the guarding of "default deny" behavior is overridden by ssrf_test.go
	// in the notify package.
	t.Setenv(notify.AllowLocalTargetsEnv, "1")
	s, _, request := trafficEvidenceServer(t)
	pg := s.m.pg

	// Create a task: A task created by the trafficEvidenceServer shared device cannot get an
	// exploration id, and the record vulnerability must provide it.
	task, err := s.m.CreateTask("通知推送测试", "推送行为验证", nil, 0, 0)
	if err != nil {
		t.Fatal(err)
	}
	taskID, err := strconv.ParseInt(task.ID, 10, 64)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { pg.Exec(`DELETE FROM tasks WHERE id=$1`, taskID) })

	var mark int64
	if err := pg.QueryRow(`SELECT COALESCE(max(id),0) FROM notification_events`).Scan(&mark); err != nil {
		t.Fatal(err)
	}
	// Let the fixture self-close: Marks an event that exists before the fixture is built as
	// assigned once.
	//
	// Why it is necessary: FanOutPendingEvents is **global**, and will expand all unassigned Curie
	// events to all matching channels. And the shared device trafficEvidenceServer itself will
	// write a vulnerability (the initial finding it returns) that may remain in other use cases.
	if _, err := pg.Exec(`UPDATE notification_events SET fanned_out = true WHERE id <= $1 AND NOT fanned_out`, mark); err != nil {
		t.Fatal(err)
	}

	f := &notifyFixture{s: s, pg: pg, request: request, n: newNotifier(s), taskID: taskID, expID: task.ExpID, cleanupMark: mark}
	t.Cleanup(func() {
		if _, err := pg.Exec(`DELETE FROM notification_events WHERE id > $1`, f.cleanupMark); err != nil {
			t.Logf("清理通知事件失败: %v", err)
		}
	})
	// The master switch must be on (other use cases may turn it off).
	if err := pg.SetBool(settingNotifyEnabled, true); err != nil {
		t.Fatal(err)
	}
	return f
}

// The path will register the push event in the same transaction as the binding point of the
// function.
func (f *notifyFixture) record(t *testing.T, vulnclass, severity string) int64 {
	t.Helper()
	out, err := f.s.evidenceStore().Record(context.Background(), db.RecordFindingInput{
		TaskID:        f.taskID,
		ExplorationID: f.expID,
		Worker:        "test",
		VulnClass:     vulnclass,
		Name:          vulnclass,
		Severity:      severity,
		Summary:       vulnclass + " 的摘要",
		Evidence:      "poc",
	}, nil)
	if err != nil {
		t.Fatalf("记录漏洞失败: %v", err)
	}
	return out.FindingID
}

