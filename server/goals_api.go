package server

import (
	"encoding/json"
	"net/http"
	"strconv"
	"strings"

	"github.com/Autumn-27/artex/db"
)

// Overview of the manual CRUD interface for goal management. Write the same set of goal nodes as
// the agent-side set_goals tool, but with the input being humans adding and deleting them directly
// on the UI; reuse "resume task" logic after addition/modification (admitTask resume: end state →
// running, unpause, queue if necessary), delete without resumption (by product decision).Each
// change handler goes beginTaskOperation/decInflight to avoid deletion of tasks in conjunction with
// the end state (in accordance with the intention CRUD).

// listGoals Returns all the goals for this task (text/vulnclass/state unpacked) for target
// management card rendering.
func (s *Server) listGoals(w http.ResponseWriter, r *http.Request) {
	t, ok := s.m.Task(r.PathValue("id"))
	if !ok {
		writeErr(w, 404, "task not found")
		return
	}
	goals, err := t.Store.ListByKind(db.KindGoal, 10000)
	if err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	writeJSON(w, 200, map[string]any{"goals": goalDTOs(goals)})
}

// addGoal Adds a new goal manually: drop (attached to the task root spawns) → write "new goal
// added" triggers planner → relive the task, letting the planner re-judge whether the new goal was
// achieved.
func (s *Server) addGoal(w http.ResponseWriter, r *http.Request) {
	t, ok := s.m.Task(r.PathValue("id"))
	if !ok {
		writeErr(w, 404, "task not found")
		return
	}
	if !s.engine.beginTaskOperation(t.ID) {
		writeErr(w, 409, "任务正在删除,无法新增目标")
		return
	}
	defer s.engine.decInflight(t.ID)

	var body struct {
		Text      string `json:"text"`
		VulnClass string `json:"vulnclass"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		writeErr(w, 400, "invalid JSON")
		return
	}
	text := strings.TrimSpace(body.Text)
	if text == "" {
		writeErr(w, 400, "目标内容不能为空")
		return
	}
	payload := map[string]any{"text": text}
	if vc := strings.TrimSpace(body.VulnClass); vc != "" {
		payload["vulnclass"] = vc
	}
	id, err := t.Store.AddGoal(payload, "human")
	if err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	if of, _ := t.Store.OriginFactID(); of > 0 && id > 0 {
		_ = t.Store.Link(of, db.RelSpawns, id) // goal descends from the task root (origin fact)
	}
	t.NotifyGoal([]string{text}) // The memory "A person added a new goal:..." triggers and wakes up the planner
	s.reviveTask(t)              // Pull completed/paused tasks back to running mode to continue running
	node, _ := t.Store.GetNode(id)
	if node == nil {
		writeErr(w, 500, "目标写入后读取失败")
		return
	}
	writeJSON(w, 200, goalDTO(node))
}

// editGoal Manually modify a target text (and vulnclass): change library → note "User changed
// target from old to new" Triggers awakening planner → resuscitate task, allowing planner to adjust
// direction to the new target.
func (s *Server) editGoal(w http.ResponseWriter, r *http.Request) {
	t, ok := s.m.Task(r.PathValue("id"))
	if !ok {
		writeErr(w, 404, "task not found")
		return
	}
	if !s.engine.beginTaskOperation(t.ID) {
		writeErr(w, 409, "任务正在删除,无法修改目标")
		return
	}
	defer s.engine.decInflight(t.ID)

	gid, err := strconv.ParseInt(r.PathValue("gid"), 10, 64)
	if err != nil || gid <= 0 {
		writeErr(w, 400, "bad goal id")
		return
	}
	var body struct {
		Text      string `json:"text"`
		VulnClass string `json:"vulnclass"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		writeErr(w, 400, "invalid JSON")
		return
	}
	text := strings.TrimSpace(body.Text)
	if text == "" {
		writeErr(w, 400, "目标内容不能为空")
		return
	}
	node, err := t.Store.GetNode(gid)
	if err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	if node == nil || node.Kind != db.KindGoal {
		writeErr(w, 404, "目标不存在")
		return
	}
	oldText := goalDTO(node).Text
	if err := t.Store.UpdateGoalPayload(gid, text, strings.TrimSpace(body.VulnClass)); err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	t.NotifyGoalEdited(oldText, text) // The memory "people changed the target from old to new" triggers and wakes up the planner
	s.reviveTask(t)                   // Consistent with the new addition: Resurrection Missions Rejudged by New Objectives
	updated, _ := t.Store.GetNode(gid)
	if updated == nil {
		writeErr(w, 500, "目标更新后读取失败")
		return
	}
	writeJSON(w, 200, goalDTO(updated))
}

// deleteGoal Manually delete a goal (hard deletion, cascaded deletion of edge/anchor): delete goal
// → note "User deleted the goal X" Triggers wake planner Re-judge remaining goals accordingly.
func (s *Server) deleteGoal(w http.ResponseWriter, r *http.Request) {
	t, ok := s.m.Task(r.PathValue("id"))
	if !ok {
		writeErr(w, 404, "task not found")
		return
	}
	if !s.engine.beginTaskOperation(t.ID) {
		writeErr(w, 409, "任务正在删除,无法删除目标")
		return
	}
	defer s.engine.decInflight(t.ID)

	gid, err := strconv.ParseInt(r.PathValue("gid"), 10, 64)
	if err != nil || gid <= 0 {
		writeErr(w, 400, "bad goal id")
		return
	}
	node, err := t.Store.GetNode(gid)
	if err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	if node == nil || node.Kind != db.KindGoal {
		writeErr(w, 404, "目标不存在")
		return
	}
	text := goalDTO(node).Text
	if err := t.Store.DeleteGoal(gid); err != nil {
		writeErr(w, 500, err.Error())
		return
	}
	t.NotifyGoalDeleted(text) // Remember "Person deleted the target:..." triggers and wakes up the planner (no revival task)
	writeJSON(w, 200, map[string]bool{"ok": true})
}
